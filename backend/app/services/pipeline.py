"""Central orchestration: audio -> ASR + VoiceID -> alignment -> MeetingLens."""
from __future__ import annotations

import time
from pathlib import Path

from ..config import LANGUAGE_NAMES
from ..utils.audio_utils import load_wav
from .alignment import assign_speakers
from .audio_processor import analyze_audio, preprocess_audio
from .meeting_analyzer import generate_meeting_summary
from .speaker_diarization import identify_speakers
from .speech_recognition import transcribe_audio, transcribe_turns


def process_meeting(audio_path: Path, *, num_speakers: int | None = None, language: str | None = None,
                    multilingual: bool = True, summarize: bool = True, output_language: str = "en",
                    enrolled: list[dict] | None = None, progress=lambda *a: None) -> dict:
    timings: dict[str, float] = {}
    t = time.perf_counter()
    progress("preprocessing", 0.05, "Resampling to 16 kHz mono and reducing noise")
    prepared = preprocess_audio(audio_path)
    analysis = analyze_audio(prepared)
    timings["preprocessing"] = round(time.perf_counter() - t, 2)

    # Speaker diarization runs on the ORIGINAL (non-denoised, resampled) audio so
    # voice characteristics are preserved; ASR uses the denoised version.
    t = time.perf_counter()
    progress("diarization", 0.2, "VoiceID: extracting ECAPA-TDNN embeddings and clustering speakers")
    voice = identify_speakers(prepared.raw_wav_path, num_speakers=num_speakers, enrolled=enrolled)
    timings["diarization"] = round(time.perf_counter() - t, 2)

    t = time.perf_counter()
    progress("transcription", 0.45, "Whisper: recognising speech and detecting language")
    if multilingual and voice["speakers"]:
        y, sr = load_wav(prepared.wav_path)
        asr = transcribe_turns(y, sr, voice["speakers"], language=language)
        aligned = asr["segments"]
        alignment_method = "per-speaker-turn transcription (language detected per turn)"
    else:
        asr = transcribe_audio(prepared.wav_path, language=language)
        progress("alignment", 0.7, "Aligning transcript with speaker turns by temporal overlap")
        aligned = assign_speakers(asr["segments"], voice["speakers"])
        for s in aligned:
            s["language"] = asr["language"]
        alignment_method = "temporal overlap (largest overlap wins, UNKNOWN below 30%)"
    timings["transcription"] = round(time.perf_counter() - t, 2)

    analysis_out, analysis_error = None, None
    if summarize and aligned:
        t = time.perf_counter()
        progress("analysis", 0.8, "MeetingLens: generating summary, decisions and action items")
        try:
            analysis_out = generate_meeting_summary(aligned, LANGUAGE_NAMES.get(output_language, "English"))
        except Exception as exc:
            analysis_error = str(exc)
        timings["analysis"] = round(time.perf_counter() - t, 2)

    # per-speaker languages + word counts
    for st in voice["speaker_stats"]:
        mine = [s for s in aligned if s["speaker_id"] == st["speaker_id"]]
        langs: dict[str, int] = {}
        for s in mine:
            langs[s.get("language") or "?"] = langs.get(s.get("language") or "?", 0) + 1
        st["languages"] = sorted(langs, key=langs.get, reverse=True)
        st["word_count"] = sum(len(s["text"].split()) for s in mine)

    voice.pop("_centroids", None)
    return {
        "audio_file": prepared.wav_path.name,
        "duration": prepared.duration,
        "language": asr.get("language"),
        "languages": asr.get("languages") or ({asr["language"]: prepared.duration} if asr.get("language") else {}),
        "transcript": aligned,
        "full_text": " ".join(s["text"] for s in aligned),
        "speakers": voice,
        "analysis": analysis_out,
        "analysis_error": analysis_error,
        "audio_analysis": analysis,
        "alignment_method": alignment_method,
        "asr_model": asr.get("model"),
        "timings": timings,
    }


def build_report_markdown(title: str, created: str, result: dict) -> str:
    def ts(t: float) -> str:
        return f"{int(t // 60):02d}:{int(t % 60):02d}"

    a = result.get("analysis") or {}
    sp = result.get("speakers") or {}
    L = [f"# {a.get('meeting_title') or title}", "",
         f"*Generated by NAS (Neural Audio System) on {created}*", "",
         f"- **Duration:** {result.get('duration', 0):.1f} s",
         f"- **Speakers detected:** {sp.get('speaker_count', 0)} ({sp.get('backend', '')})",
         f"- **Languages:** {', '.join(LANGUAGE_NAMES.get(l, l) for l in (result.get('languages') or {}))}",
         f"- **ASR model:** Whisper {result.get('asr_model', '')}", ""]
    if a:
        L += ["## Summary", "", a.get("summary", ""), ""]
        if a.get("key_points"):
            L += ["## Key points", ""] + [f"- {k['point']} *({k['speaker']})*" for k in a["key_points"]] + [""]
        if a.get("decisions"):
            L += ["## Decisions", ""] + [f"- {d['decision']} — “{d['evidence']}”" for d in a["decisions"]] + [""]
        if a.get("action_items"):
            L += ["## Action items", "", "| Task | Owner | Deadline |", "|---|---|---|"]
            L += [f"| {x['task']} | {x['owner']} | {x['deadline']} |" for x in a["action_items"]] + [""]
        if a.get("topics"):
            L += ["## Topics", "", ", ".join(a["topics"]), ""]
        if a.get("missing_information"):
            L += ["## Unclear / missing information", ""] + [f"- {m}" for m in a["missing_information"]] + [""]
    elif result.get("analysis_error"):
        L += ["## Summary", "", f"_Summary not available: {result['analysis_error']}_", ""]
    if sp.get("speaker_stats"):
        L += ["## Speakers", "", "| Speaker | Talk time | Share | Turns | Languages |", "|---|---|---|---|---|"]
        for s in sp["speaker_stats"]:
            L.append(f"| {s['speaker_id']} | {s['total_duration']:.1f} s | {s['percentage']}% | "
                     f"{s['segment_count']} | {', '.join(s.get('languages', []))} |")
        L.append("")
    L += ["## Transcript", ""]
    for s in result.get("transcript", []):
        flag = " (uncertain speaker)" if s.get("uncertain") else ""
        L.append(f"**[{ts(s['start'])}–{ts(s['end'])}] {s['speaker_id']}{flag}** "
                 f"_{s.get('language', '')}_: {s['text']}  ")
        if s.get("translation"):
            L.append(f"&nbsp;&nbsp;↳ {s['translation']}  ")
    return "\n".join(L) + "\n"
